/** Longest-prefix lookup on a digit-only ΚΑΔ code. */
export function lookupKadPrefixes(digits: string): { key: string; prefixes: string[] } | undefined {
  for (let len = Math.min(digits.length, 4); len >= 2; len--) {
    const key = digits.slice(0, len);
    const prefixes = KAD_CPV_PREFIXES[key];
    if (prefixes) return { key, prefixes };
  }
  return undefined;
}
